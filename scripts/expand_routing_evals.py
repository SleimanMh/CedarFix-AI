def append_to_eval(path: pathlib.Path, new_cases: list):
    existing = [json.loads(l) for l in open(path, encoding="utf-8")]
    existing_ids = {c["id"] for c in existing}
    added = [c for c in new_cases if c["id"] not in existing_ids]
    all_cases = existing + added
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for c in all_cases:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    return len(existing), len(added), len(all_cases)


